const DICT: Record<Locale, Record<UIKey, string>> = { en, hi };

export function useTranslations(locale: Locale) {
  return (key: UIKey): string => DICT[locale][key];
}

/** Picks the right half of a { en, hi } field from the data. */
export function pick<T>(field: { en: T; hi: T }, locale: Locale): T {
  return field[locale];
}
